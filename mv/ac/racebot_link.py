"""Python side of the CSP Lua app "MV Race Bot" (``mv/ac/plugin/apps/lua/mv_racebot``) - race bot stage 5.

The owner drives car 0; our driver drives car 1, an AI car of the same model (WP65, D-044).  The app takes
that car over (``physics.setAINoInput`` so the game's AI stops pressing pedals - for AI cars the game uses
the *larger* of the AI's and our gas/brake - then ``ac.overrideCarControls(1)``), applies our steering and
pedals, and publishes the bot car's state and every other car's position, so the driver sees its opponents.

Two shared-memory blocks, same scheme as MV Bridge (:mod:`mv.ac.bridge.plugin_link`): natural C alignment,
the C text of each layout generated by :func:`c_layout` and embedded verbatim in the Lua file (a test checks
they are identical), seqlock (odd ``seq`` = being written).

* ``Local\\mv_racebot_cmd_v1``   Python -> Lua: enable, which car, steering (AC sign: +1 = RIGHT), pedals
* ``Local\\mv_racebot_state_v1`` Lua -> Python: session state, the bot car, up to 8 other cars, and whether
  the car really follows our pedals (``control_ok``) - the one thing only the game can confirm.
"""

from __future__ import annotations

import ctypes
import math
import mmap
import time
from ctypes import c_double, c_float, c_int32, c_uint32
from dataclasses import dataclass, field

import numpy as np

from mv.ac.bridge.frames import ac_local_to_body, ac_world_to_map3
from mv.ac.bridge.plugin_link import c_layout

__all__ = ["CMD_MAP_NAME", "STATE_MAP_NAME", "CMD_MAGIC", "STATE_MAGIC", "LAYOUT_VERSION", "MAX_OTHERS",
           "RaceBotCmd", "RaceBotStateRaw", "CarSnapshot", "RaceBotState", "RaceBotLink", "decode", "c_layout",
           "TAKEOVER_NO_INPUT", "TAKEOVER_THROTTLE_LIMIT"]

CMD_MAP_NAME = "Local\\mv_racebot_cmd_v1"
STATE_MAP_NAME = "Local\\mv_racebot_state_v1"
CMD_MAGIC = 0x31424D43      # b"CMB1" little-endian
STATE_MAGIC = 0x31425353    # b"SSB1" little-endian
LAYOUT_VERSION = 1
MAX_OTHERS = 8

#: how the app silences the game's AI on the bot car (see the Lua file): 1 = physics.setAINoInput,
#: 2 = physics.setAIThrottleLimit(0) (fallback: AI gas off, but the AI may still brake)
TAKEOVER_NO_INPUT = 1
TAKEOVER_THROTTLE_LIMIT = 2


class RaceBotCmd(ctypes.Structure):
    _fields_ = [
        ("magic", c_uint32),
        ("version", c_uint32),
        ("seq", c_uint32),
        ("enable", c_uint32),          # 1 = drive the bot car, 0 = give it back to the game's AI
        ("bot_index", c_int32),        # 0-based car index of the bot (an AI car)
        ("takeover", c_int32),         # TAKEOVER_*
        ("steer", c_float),            # AC convention, +1 = full RIGHT
        ("gas", c_float),              # 0..1
        ("brake", c_float),            # 0..1
        ("stale_timeout_s", c_float),  # Lua fail-safe (brake, wheel straight) if seq stops changing
        ("host_time_ms", c_uint32),
    ]


class RaceBotStateRaw(ctypes.Structure):
    _fields_ = [
        ("magic", c_uint32),
        ("version", c_uint32),
        ("seq", c_uint32),
        ("frame", c_uint32),
        ("game_time_s", c_double),
        ("bot_index", c_int32),
        ("cars_count", c_int32),
        ("session_started", c_int32),
        ("in_menu", c_int32),
        ("is_paused", c_int32),
        ("physics_allowed", c_int32),
        ("takeover_active", c_int32),    # the AI-silencing call succeeded
        ("override_active", c_int32),
        ("failsafe_active", c_int32),
        ("control_ok", c_int32),         # the car's gas and brake equal ours (last ~0.5 s)
        ("time_to_start_s", c_float),
        ("cmd_seq_seen", c_uint32),
        # the bot car (AC world / car-local axes; converted in decode())
        ("position", c_float * 3),
        ("velocity", c_float * 3),
        ("local_velocity", c_float * 3),
        ("local_angular_velocity", c_float * 3),
        ("look", c_float * 3),
        ("gas", c_float),
        ("brake", c_float),
        ("steer_deg", c_float),
        ("rpm", c_float),
        ("kers_charge", c_float),
        ("spline", c_float),
        ("collision_depth", c_float),
        ("gear", c_int32),               # 1 = first, 0 = neutral, -1 = reverse
        ("wheels_outside", c_int32),
        ("lap_count", c_int32),
        ("lap_time_ms", c_int32),
        ("last_lap_ms", c_int32),
        ("best_lap_ms", c_int32),
        ("race_position", c_int32),
        ("collided_with", c_int32),
        # the other cars (slot k: car other_index[k]; other_active 0 = empty slot)
        ("other_index", c_int32 * MAX_OTHERS),
        ("other_active", c_int32 * MAX_OTHERS),
        ("other_position", c_float * (3 * MAX_OTHERS)),
        ("other_velocity", c_float * (3 * MAX_OTHERS)),
        ("other_look", c_float * (3 * MAX_OTHERS)),
    ]


@dataclass
class CarSnapshot:
    """One car in the project's frames: map position (m), yaw (rad, CCW from +map_x), body velocity."""
    index: int
    x: float
    y: float
    yaw: float
    vx: float                       # forward, m/s
    vy: float                       # to the left, m/s


@dataclass
class RaceBotState:
    seq: int
    game_time_s: float
    bot_index: int
    cars_count: int
    session_started: bool
    in_menu: bool
    is_paused: bool
    physics_allowed: bool
    takeover_active: bool
    override_active: bool
    failsafe_active: bool
    control_ok: bool
    time_to_start_s: float
    bot: CarSnapshot
    yaw_rate: float                 # rad/s, + = turning left
    gas: float
    brake: float
    rpm: float
    kers_charge: float
    gear: int
    wheels_outside: int
    lap_count: int
    lap_time_s: float
    last_lap_s: float
    best_lap_s: float
    race_position: int
    collision_depth: float
    others: list[CarSnapshot] = field(default_factory=list)


def _yaw(look_ac) -> float:
    f = ac_world_to_map3(look_ac)
    return float(math.atan2(f[1], f[0]))


def _snapshot(index: int, pos_ac, vel_ac, look_ac) -> CarSnapshot:
    p, v = ac_world_to_map3(pos_ac), ac_world_to_map3(vel_ac)
    yaw = _yaw(look_ac)
    c, s = math.cos(yaw), math.sin(yaw)
    return CarSnapshot(index, float(p[0]), float(p[1]), yaw, float(v[0] * c + v[1] * s), float(-v[0] * s + v[1] * c))


def decode(raw: RaceBotStateRaw) -> RaceBotState:
    lv = ac_local_to_body(raw.local_velocity)
    w = ac_local_to_body(raw.local_angular_velocity)
    bot = _snapshot(raw.bot_index, raw.position, raw.velocity, raw.look)
    bot.vx, bot.vy = float(lv[0]), float(lv[1])          # the car's own local velocity: exact
    others = []
    for k in range(MAX_OTHERS):
        if raw.other_active[k]:
            sl = slice(3 * k, 3 * k + 3)
            others.append(_snapshot(raw.other_index[k], raw.other_position[sl], raw.other_velocity[sl],
                                    raw.other_look[sl]))
    ms = lambda v: v / 1000.0 if v > 0 else math.nan  # noqa: E731
    return RaceBotState(
        seq=raw.seq, game_time_s=raw.game_time_s, bot_index=raw.bot_index, cars_count=raw.cars_count,
        session_started=bool(raw.session_started), in_menu=bool(raw.in_menu), is_paused=bool(raw.is_paused),
        physics_allowed=bool(raw.physics_allowed), takeover_active=bool(raw.takeover_active),
        override_active=bool(raw.override_active), failsafe_active=bool(raw.failsafe_active),
        control_ok=bool(raw.control_ok), time_to_start_s=raw.time_to_start_s, bot=bot, yaw_rate=float(w[2]),
        gas=raw.gas, brake=raw.brake, rpm=raw.rpm, kers_charge=raw.kers_charge, gear=raw.gear,
        wheels_outside=raw.wheels_outside, lap_count=raw.lap_count, lap_time_s=ms(raw.lap_time_ms),
        last_lap_s=ms(raw.last_lap_ms), best_lap_s=ms(raw.best_lap_ms), race_position=raw.race_position,
        collision_depth=raw.collision_depth, others=others)


class RaceBotLink:
    """Both mappings on the Python side (they are ours, not the game's: create-or-open is fine)."""

    def __init__(self, bot_index: int = 1, stale_timeout_s: float = 0.5,
                 cmd_name: str = CMD_MAP_NAME, state_name: str = STATE_MAP_NAME):
        self._cmd_mm = mmap.mmap(-1, ctypes.sizeof(RaceBotCmd), tagname=cmd_name)
        self._state_mm = mmap.mmap(-1, ctypes.sizeof(RaceBotStateRaw), tagname=state_name)
        self._cmd = RaceBotCmd.from_buffer(self._cmd_mm)
        self._state_addr = ctypes.addressof(RaceBotStateRaw.from_buffer(self._state_mm))
        self.bot_index, self.stale_timeout_s = int(bot_index), float(stale_timeout_s)
        self.takeover = TAKEOVER_NO_INPUT
        self.release()

    def _write(self, **fields) -> None:
        c = self._cmd
        seq = int(c.seq)
        if seq % 2:
            seq += 1
        c.seq = (seq + 1) & 0xFFFFFFFF
        c.magic, c.version = CMD_MAGIC, LAYOUT_VERSION
        c.bot_index, c.takeover, c.stale_timeout_s = self.bot_index, self.takeover, self.stale_timeout_s
        for k, v in fields.items():
            setattr(c, k, v)
        c.host_time_ms = int(time.monotonic() * 1000) & 0xFFFFFFFF
        c.seq = (seq + 2) & 0xFFFFFFFF

    def drive(self, steer_left: float, gas: float, brake: float) -> None:
        """One control frame in the PROJECT convention (+steer = left); the game wants +1 = right."""
        self._write(enable=1, steer=-float(np.clip(steer_left, -1, 1)), gas=float(np.clip(gas, 0, 1)),
                    brake=float(np.clip(brake, 0, 1)))

    def release(self) -> None:
        """Give the car back to the game's AI."""
        self._write(enable=0, steer=0.0, gas=0.0, brake=0.0)

    def read(self, retries: int = 8) -> RaceBotState | None:
        size = ctypes.sizeof(RaceBotStateRaw)
        seq_field = ctypes.c_uint32.from_address(self._state_addr + RaceBotStateRaw.seq.offset)
        for _ in range(retries):
            s1 = seq_field.value
            if s1 % 2:
                continue
            raw = RaceBotStateRaw.from_buffer_copy(ctypes.string_at(self._state_addr, size))
            if seq_field.value == s1:
                if raw.magic != STATE_MAGIC or raw.version != LAYOUT_VERSION:
                    return None
                return decode(raw)
        return None

    def close(self) -> None:
        if self._cmd_mm is None:
            return
        try:
            self.release()
        except Exception:
            pass
        del self._cmd
        self._cmd_mm.close()
        self._state_mm.close()
        self._cmd_mm = self._state_mm = None
