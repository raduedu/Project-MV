"""Python side of the CSP Lua app "MV Bridge" (``mv/ac/plugin/apps/lua/mv_bridge``).

Why a Lua app and shared memory?
    CSP (Custom Shaders Patch, installed: 0.2.11 build 3465) exposes to Lua
    *apps* ``ac.overrideCarControls(carIndex)`` — documented in the shipped SDK
    (``extension/internal/lua-sdk/ac_apps/lib.lua``) as "Access car controls
    overwriting. Easier than simulating inputs with fake gamepads and
    keypresses."  That gives steering/throttle/brake/gear control with *no
    virtual-device driver*.  The same SDK documents
    ``ac.writeMemoryMappedFile(name, layout)`` which opens/creates the named
    mapping ``Local\\<name>`` with a C-struct layout; CSP itself uses this to
    talk to external processes (its CEF browser and Mumble helpers).  So the
    app and this module share two small structs:

    * ``Local\\mv_bridge_cmd_v1``   — Python writes, Lua reads (controls, resets)
    * ``Local\\mv_bridge_state_v1`` — Lua writes, Python reads (extra telemetry
      that the Kunos pages lack: exact orientation vectors, track-relative
      lateral position, collisions, reset results, ...)

Layout rules
    Both structs use *natural* C alignment (no pragma pack) because LuaJIT FFI
    lays out ``ac.writeMemoryMappedFile`` layouts like a C compiler; ctypes'
    default alignment on x64 Windows matches.  The exact C text of each layout
    is generated by :func:`c_layout` and the Lua file embeds the same text;
    ``tests/test_ac_bridge.py`` asserts they are identical, so the two sides
    cannot drift apart silently.

Consistency (seqlock)
    Writer: ``seq += 1`` (odd = writing) → write fields → ``seq += 1`` (even).
    Reader: read ``seq`` (must be even) → copy → re-read ``seq`` (must equal).

Steering sign
    The cmd struct carries steering in **AC's convention: +1 = full right**
    (verified from CSP's bundled ``extension/lua/mouse-steering`` script, where
    a rightward mouse delta increases ``state.steer``).  Callers of
    :mod:`mv.ac.bridge.backends` use the *project* convention (+1 = left) and
    the backend negates.
"""

from __future__ import annotations

import ctypes
import mmap
import time
from ctypes import c_double, c_float, c_int32, c_uint32
from dataclasses import dataclass
from enum import IntEnum

import numpy as np

from .frames import ac_local_to_body, ac_world_to_map3

__all__ = [
    "CMD_MAP_NAME", "STATE_MAP_NAME", "CMD_MAGIC", "STATE_MAGIC", "LAYOUT_VERSION",
    "PluginCmd", "PluginStateRaw", "PluginState", "PluginLink", "ResetCommand",
    "ResetResult", "c_layout",
]

CMD_MAP_NAME = "Local\\mv_bridge_cmd_v1"
STATE_MAP_NAME = "Local\\mv_bridge_state_v1"
CMD_MAGIC = 0x31444D43     # b"CMD1" little-endian
STATE_MAGIC = 0x31545353   # b"SST1" little-endian
LAYOUT_VERSION = 1


class ResetCommand(IntEnum):
    """Episode-control commands executed by the Lua app (see docs §6)."""

    NONE = 0
    RESET_CAR = 1        # ac.resetCar(): back onto track, stationary (offline basic modes)
    TELEPORT_PITS = 2    # ac.tryToTeleportToPits()
    RESTART_SESSION = 3  # ac.tryToRestartSession() (offline only)
    TELEPORT_SPLINE = 4  # physics.setCarPosition/Velocity (needs physics.allowed())
    SAVE_STATE = 5       # ac.saveCarStateAsync() -> slot
    LOAD_STATE = 6       # ac.loadCarState(slot) (offline basic modes)
    STEP_BACK = 7        # ac.takeAStepBack()


class ResetResult(IntEnum):
    PENDING = 0
    OK = 1
    FAILED = -1               # the CSP call returned false
    NOT_ALLOWED_IN_SESSION = -2  # ac.isCarResetAllowed() == false
    PHYSICS_NOT_ALLOWED = -3     # physics.allowed() == false (track permission)
    EMPTY_SLOT = -4
    UNKNOWN_COMMAND = -5
    LUA_ERROR = -6


class PluginCmd(ctypes.Structure):
    """Python -> Lua.  Natural alignment; all members 4 bytes."""

    _fields_ = [
        ("magic", c_uint32),
        ("version", c_uint32),
        ("seq", c_uint32),
        ("enable", c_uint32),          # 1 = override controls, 0 = release to user
        ("steer", c_float),            # AC convention, +1 = full RIGHT
        ("gas", c_float),              # 0..1
        ("brake", c_float),            # 0..1
        ("clutch", c_float),           # 1 = pedal released (engaged), 0 = pressed
        ("handbrake", c_float),        # 0..1
        ("gear_up_count", c_int32),    # edge counters: Lua fires gearUp on change
        ("gear_down_count", c_int32),
        ("requested_gear", c_int32),   # 0 = keep, -1 = R, n = gear n
        ("stale_timeout_s", c_float),  # Lua fail-safe if seq stops changing
        ("reset_seq", c_uint32),       # Lua executes reset_cmd when this changes
        ("reset_cmd", c_int32),
        ("reset_slot", c_int32),
        ("reset_spline", c_float),
        ("reset_speed", c_float),      # m/s along track direction
        ("reset_lateral", c_float),    # -1 left edge .. 0 centre .. +1 right edge
        ("host_time_ms", c_uint32),    # Python monotonic ms (diagnostics)
    ]


class PluginStateRaw(ctypes.Structure):
    """Lua -> Python.  Natural alignment (doubles start at offset 16)."""

    _fields_ = [
        ("magic", c_uint32),
        ("version", c_uint32),
        ("seq", c_uint32),
        ("frame", c_uint32),
        ("game_time_s", c_double),       # ac.getSim().gameTime
        ("car_timestamp_ms", c_double),  # car.timestamp (time of last physics record)
        ("lua_clock_s", c_double),       # os.preciseClock()
        ("position", c_float * 3),       # AC world axes (X, Y up, Z)
        ("velocity", c_float * 3),
        ("local_velocity", c_float * 3),
        ("local_angular_velocity", c_float * 3),
        ("look", c_float * 3),           # unit forward vector, world
        ("up", c_float * 3),             # unit up vector, world
        ("acceleration_g", c_float * 3),
        ("spline", c_float),
        ("track_lateral", c_float),      # ac.worldCoordinateToTrack(pos).x
        ("track_length_m", c_float),
        ("steer_deg", c_float),          # steering-wheel angle, deg
        ("collision_depth", c_float),
        ("fps", c_float),
        ("collided_with", c_int32),
        ("collision_count", c_int32),
        ("wheels_outside", c_int32),
        ("reset_counter", c_int32),
        ("lap_valid", c_int32),
        ("lap_cuts", c_int32),
        ("in_pitlane", c_int32),
        ("in_pit", c_int32),
        ("physics_allowed", c_int32),
        ("reset_allowed", c_int32),
        ("override_active", c_int32),
        ("failsafe_active", c_int32),
        ("is_paused", c_int32),
        ("ai_controlled", c_int32),
        ("cmd_seq_seen", c_uint32),
        ("reset_seq_done", c_uint32),
        ("reset_result", c_int32),
        ("saved_slots_mask", c_int32),
        ("csp_version", c_int32),
        ("teleport_dir_sign", c_int32),
    ]


_C_NAMES = {
    c_uint32: "uint32_t", c_int32: "int32_t", c_float: "float", c_double: "double",
}


def c_layout(struct: type[ctypes.Structure]) -> str:
    """C struct *body* for ``ac.writeMemoryMappedFile`` (one member per line)."""
    lines = []
    for name, typ in struct._fields_:
        if hasattr(typ, "_length_"):
            lines.append(f"{_C_NAMES[typ._type_]} {name}[{typ._length_}];")
        else:
            lines.append(f"{_C_NAMES[typ]} {name};")
    return "\n".join(lines)


@dataclass(frozen=True)
class PluginState:
    """Decoded :class:`PluginStateRaw` in the *project* convention.

    Axes: world quantities (position, velocity, forward, up) in the map frame
    (map_x = AC X, map_y = -AC Z, z up); body quantities (local_*) in x
    forward, y left, z up.  ``yaw``/``pitch``/
    ``roll`` are exact here (from the orientation vectors), unlike the Kunos
    ``heading``/``pitch``/``roll`` whose conventions are undocumented.
    """

    seq: int
    frame: int
    game_time_s: float
    car_timestamp_s: float
    lua_clock_s: float
    position: np.ndarray
    velocity: np.ndarray
    local_velocity: np.ndarray
    local_angular_velocity: np.ndarray
    forward: np.ndarray
    up: np.ndarray
    yaw: float
    pitch: float
    roll: float
    spline: float
    track_lateral: float
    track_length_m: float
    steer_deg: float
    collision_depth: float
    fps: float
    collided_with: int
    collision_count: int
    wheels_outside: int
    reset_counter: int
    lap_valid: bool
    lap_cuts: int
    in_pitlane: bool
    in_pit: bool
    physics_allowed: bool
    reset_allowed: bool
    override_active: bool
    failsafe_active: bool
    is_paused: bool
    ai_controlled: bool
    cmd_seq_seen: int
    reset_seq_done: int
    reset_result: int
    saved_slots_mask: int
    csp_version: int
    teleport_dir_sign: int


def decode_plugin_state(raw: PluginStateRaw) -> PluginState:
    _w, _b = ac_world_to_map3, ac_local_to_body
    fwd = _w(raw.look)
    up = _w(raw.up)
    left = np.cross(up, fwd)
    yaw = float(np.arctan2(fwd[1], fwd[0]))
    # Right-hand rule about our axes: pitch about +y (left) => nose DOWN positive;
    # roll about +x (forward) => right side DOWN positive.
    pitch = float(-np.arcsin(np.clip(fwd[2], -1.0, 1.0)))
    roll = float(np.arctan2(left[2], up[2])) if np.linalg.norm(left) > 1e-6 else 0.0
    return PluginState(
        seq=raw.seq, frame=raw.frame, game_time_s=raw.game_time_s,
        car_timestamp_s=raw.car_timestamp_ms / 1000.0, lua_clock_s=raw.lua_clock_s,
        position=_w(raw.position), velocity=_w(raw.velocity),
        local_velocity=_b(raw.local_velocity),
        local_angular_velocity=_b(raw.local_angular_velocity),
        forward=fwd, up=up, yaw=yaw, pitch=pitch, roll=roll,
        spline=raw.spline, track_lateral=raw.track_lateral,
        track_length_m=raw.track_length_m, steer_deg=raw.steer_deg,
        collision_depth=raw.collision_depth, fps=raw.fps,
        collided_with=raw.collided_with, collision_count=raw.collision_count,
        wheels_outside=raw.wheels_outside, reset_counter=raw.reset_counter,
        lap_valid=bool(raw.lap_valid), lap_cuts=raw.lap_cuts,
        in_pitlane=bool(raw.in_pitlane), in_pit=bool(raw.in_pit),
        physics_allowed=bool(raw.physics_allowed), reset_allowed=bool(raw.reset_allowed),
        override_active=bool(raw.override_active), failsafe_active=bool(raw.failsafe_active),
        is_paused=bool(raw.is_paused), ai_controlled=bool(raw.ai_controlled),
        cmd_seq_seen=raw.cmd_seq_seen, reset_seq_done=raw.reset_seq_done,
        reset_result=raw.reset_result, saved_slots_mask=raw.saved_slots_mask,
        csp_version=raw.csp_version, teleport_dir_sign=raw.teleport_dir_sign,
    )


class PluginLink:
    """Owns both bridge mappings on the Python side.

    Python *creates or opens* these two mappings (they are ours, not AC's, so
    using ``mmap`` with a tagname is fine).  Sizes on both sides are identical
    by construction, so whichever process starts first creates the object and
    the other opens it.
    """

    def __init__(self, cmd_name: str = CMD_MAP_NAME, state_name: str = STATE_MAP_NAME,
                 stale_timeout_s: float = 0.5):
        self._cmd_mm = mmap.mmap(-1, ctypes.sizeof(PluginCmd), tagname=cmd_name)
        self._state_mm = mmap.mmap(-1, ctypes.sizeof(PluginStateRaw), tagname=state_name)
        self._cmd = PluginCmd.from_buffer(self._cmd_mm)
        self._state_addr = ctypes.addressof(PluginStateRaw.from_buffer(self._state_mm))
        self.stale_timeout_s = float(stale_timeout_s)
        self._gear_up = 0
        self._gear_down = 0
        self._last_state_seq: int | None = None
        self._last_state_change = 0.0
        c = self._cmd
        # Keep the reset sequence that may already be in the mapping so the Lua
        # side does not see a "new" command when we (re)open it.
        self._reset_seq = int(c.reset_seq)
        self._write(enable=0, steer=0.0, gas=0.0, brake=0.0, clutch=1.0, handbrake=0.0,
                    requested_gear=0)

    # ----------------------------------------------------------------- writing
    def _write(self, **fields) -> None:
        c = self._cmd
        seq = int(c.seq)
        if seq % 2:
            seq += 1
        c.seq = (seq + 1) & 0xFFFFFFFF          # odd: write in progress
        c.magic = CMD_MAGIC
        c.version = LAYOUT_VERSION
        c.stale_timeout_s = self.stale_timeout_s
        for k, v in fields.items():
            setattr(c, k, v)
        c.host_time_ms = int(time.monotonic() * 1000) & 0xFFFFFFFF
        c.seq = (seq + 2) & 0xFFFFFFFF          # even: consistent

    def write_controls(self, steer_ac: float, gas: float, brake: float, clutch: float = 1.0,
                       handbrake: float = 0.0, gear_up: bool = False, gear_down: bool = False,
                       requested_gear: int = 0) -> int:
        """Write one control frame; returns the command sequence number."""
        if gear_up:
            self._gear_up += 1
        if gear_down:
            self._gear_down += 1
        self._write(enable=1, steer=float(steer_ac), gas=float(gas), brake=float(brake),
                    clutch=float(clutch), handbrake=float(handbrake),
                    gear_up_count=self._gear_up, gear_down_count=self._gear_down,
                    requested_gear=int(requested_gear))
        return int(self._cmd.seq)

    def release(self) -> None:
        """Hand the car back to the user's own controls."""
        self._write(enable=0, steer=0.0, gas=0.0, brake=0.0, clutch=1.0, handbrake=0.0,
                    requested_gear=0)

    def request(self, command: ResetCommand, slot: int = 0, spline: float = 0.0,
                speed: float = 0.0, lateral: float = 0.0) -> int:
        """Queue an episode-control command; returns its sequence number."""
        self._reset_seq = (self._reset_seq + 1) & 0xFFFFFFFF
        self._write(reset_seq=self._reset_seq, reset_cmd=int(command), reset_slot=int(slot),
                    reset_spline=float(spline) % 1.0, reset_speed=float(speed),
                    reset_lateral=float(lateral))
        return self._reset_seq

    def wait_result(self, seq: int, timeout_s: float = 3.0) -> ResetResult:
        """Block until the Lua app reports completion of request ``seq``."""
        deadline = time.perf_counter() + timeout_s
        while time.perf_counter() < deadline:
            st = self.read_raw()
            if st is not None and st.reset_seq_done == seq and st.reset_result != 0:
                try:
                    return ResetResult(st.reset_result)
                except ValueError:
                    return ResetResult.FAILED
            time.sleep(0.005)
        raise TimeoutError(f"MV Bridge Lua app did not complete request {seq} within "
                           f"{timeout_s:.1f}s (is the app installed and running?)")

    # ----------------------------------------------------------------- reading
    def read_raw(self, retries: int = 8) -> PluginStateRaw | None:
        size = ctypes.sizeof(PluginStateRaw)
        seq_field = ctypes.c_uint32.from_address(self._state_addr + PluginStateRaw.seq.offset)
        for _ in range(retries):
            s1 = seq_field.value
            if s1 % 2:
                continue
            raw = PluginStateRaw.from_buffer_copy(ctypes.string_at(self._state_addr, size))
            if seq_field.value == s1:
                if raw.magic != STATE_MAGIC or raw.version != LAYOUT_VERSION:
                    return None
                now = time.perf_counter()
                if raw.seq != self._last_state_seq:
                    self._last_state_seq = raw.seq
                    self._last_state_change = now
                return raw
        return None

    def read_state(self) -> PluginState | None:
        raw = self.read_raw()
        return None if raw is None else decode_plugin_state(raw)

    def alive(self, max_age_s: float = 0.5) -> bool:
        """True if the Lua app has published a new frame within ``max_age_s``."""
        if self.read_raw() is None:
            return False
        return (time.perf_counter() - self._last_state_change) <= max_age_s

    @property
    def cmd(self) -> PluginCmd:
        return self._cmd

    def close(self, release: bool = True) -> None:
        if self._cmd_mm is None:
            return
        if release:
            try:
                self.release()
            except Exception:
                pass
        del self._cmd
        self._cmd_mm.close()
        self._state_mm.close()
        self._cmd_mm = None
        self._state_mm = None
